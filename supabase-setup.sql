create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- 1) 회원 프로필 (auth.users 와 1:1)
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  name        text,
  approved    boolean not null default false,   -- 도립맨님이 승인해야 true
  role        text    not null default 'member' check (role in ('member', 'admin')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table  public.profiles is '도립 물구나무 훈련소 회원 프로필';
comment on column public.profiles.approved is '관리자가 승인하면 true (가이드북 영상 열람 가능)';
comment on column public.profiles.role is 'member | admin';

-- -----------------------------------------------------------------------------
-- 2) 가이드북 영상
--    영상 파일 자체를 저장하지 않고 유튜브·비메오·mp4 '주소'만 저장합니다.
-- -----------------------------------------------------------------------------
create table if not exists public.videos (
  id          bigint generated by default as identity primary key,
  chapter     text        not null default '기타',
  title       text        not null,
  description text,
  video_url   text        not null,
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists videos_chapter_sort_idx
  on public.videos (chapter, sort_order, created_at);

-- -----------------------------------------------------------------------------
-- 3) 도우미 함수
--    security definer 로 두어 profiles 정책이 자기 테이블을 다시 조회하다
--    무한 재귀(infinite recursion)에 빠지지 않게 합니다.
-- -----------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.is_approved_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and (approved = true or role = 'admin')
  );
$$;

-- -----------------------------------------------------------------------------
-- 4) 회원가입 → 프로필 자동 생성
--    승인 전에는 approved = false, role = 'member' 로 시작합니다.
--    이름은 가입 화면에서 입력한 값(raw_user_meta_data.name)을 사용합니다.
-- -----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, name, approved, role)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      '회원'
    ),
    false,
    'member'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- -----------------------------------------------------------------------------
-- 5) 권한 상승 방지 장치
--    회원이 스스로 approved/role 을 바꿔 영상을 열어 보는 것을 막습니다.
--    (관리자이거나, SQL Editor·service_role 처럼 로그인 사용자가 없는 경우는 통과)
-- -----------------------------------------------------------------------------
create or replace function public.guard_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or public.is_admin() then
    return new;
  end if;
  new.id       := old.id;
  new.email    := old.email;
  new.approved := old.approved;
  new.role     := old.role;
  return new;
end;
$$;

drop trigger if exists guard_profile_privileges on public.profiles;
create trigger guard_profile_privileges
  before update on public.profiles
  for each row execute function public.guard_profile_privileges();

-- -----------------------------------------------------------------------------
-- 6) updated_at 자동 갱신
-- -----------------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists touch_profiles_updated_at on public.profiles;
create trigger touch_profiles_updated_at
  before update on public.profiles
  for each row execute function public.touch_updated_at();

drop trigger if exists touch_videos_updated_at on public.videos;
create trigger touch_videos_updated_at
  before update on public.videos
  for each row execute function public.touch_updated_at();

-- -----------------------------------------------------------------------------
-- 7) Row Level Security — 규칙 그대로 잠급니다
-- -----------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.videos   enable row level security;

-- 7-1) profiles : 본인 것 1행만 조회, 관리자는 전체 조회
drop policy if exists "profiles_select_own"   on public.profiles;
create policy "profiles_select_own"
  on public.profiles for select
  to authenticated
  using (id = auth.uid());

drop policy if exists "profiles_select_admin" on public.profiles;
create policy "profiles_select_admin"
  on public.profiles for select
  to authenticated
  using (public.is_admin());

-- 7-2) profiles : 본인 이름 정도만 수정 가능(승인값·권한은 위 트리거가 되돌림),
--       관리자는 전체 수정 가능(승인/승인 취소)
drop policy if exists "profiles_update_own"   on public.profiles;
create policy "profiles_update_own"
  on public.profiles for update
  to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin"
  on public.profiles for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- 7-3) profiles : insert/delete 정책은 만들지 않습니다.
--      프로필 행은 가입 시 트리거(security definer)가 만들고,
--      클라이언트가 직접 insert 하면 approved=true 를 스스로 넣을 수 있기 때문입니다.
drop policy if exists "profiles_insert_own" on public.profiles;
drop policy if exists "profiles_delete_own" on public.profiles;

-- 7-4) videos : 승인된 회원 또는 관리자만 조회
drop policy if exists "videos_select_approved" on public.videos;
create policy "videos_select_approved"
  on public.videos for select
  to authenticated
  using (public.is_approved_member());

-- 7-5) videos : 관리자만 추가·수정·삭제
drop policy if exists "videos_insert_admin" on public.videos;
create policy "videos_insert_admin"
  on public.videos for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "videos_update_admin" on public.videos;
create policy "videos_update_admin"
  on public.videos for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "videos_delete_admin" on public.videos;
create policy "videos_delete_admin"
  on public.videos for delete
  to authenticated
  using (public.is_admin());

-- 7-6) 권한 부여 (RLS 가 실제 행을 걸러냅니다)
grant usage on schema public to anon, authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.videos to authenticated;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_approved_member() to authenticated;

